export const AMAZON_STORE_ID = 'esstri-21';
export const AMAZON_TRACKING_TAG = 'karat.info-21';

export function getAmazonAffiliateUrl(queryOrAsin: string, asin?: string): string {
  const tag = AMAZON_TRACKING_TAG;
  if (asin) {
    return `https://www.amazon.de/dp/${asin}?tag=${tag}`;
  }
  return `https://www.amazon.de/s?k=${encodeURIComponent(queryOrAsin)}&tag=${tag}`;
}

export function getProductUrl(product: JewelryProduct): string {
  return getAmazonAffiliateUrl(product.amazonSearchQuery, product.asin);
}

